"""Render every pilot portrait at the sizes the game uses and write src/pilots_data.ts (base64 PNGs).
Run from the repo root: python3 tools/pilots/export.py   (needs numpy + Pillow)
Sizes: 136 = final-duel card and pilot-select preview, 48 = HUD and select cards, 40 = target panel."""
import base64, io, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pilots import portrait

ORDER = ["ACE", "NOVA", "UNIT-9", "ZEPHYR", "TITAN", "KITSUNE", "EMBER"]
SIZES = [136, 48, 40]


def b64(img):
    buf = io.BytesIO(); img.save(buf, "PNG", optimize=True); return base64.b64encode(buf.getvalue()).decode()


lines = ["// GENERATED by tools/pilots/export.py - do not edit. Pilot portraits as base64 PNGs, rendered natively per size.",
         "export const PILOT_IMAGES: { name: string; s136: string; s48: string; s40: string }[] = ["]
total = 0
for n in ORDER:
    d = {s: b64(portrait(n, s)) for s in SIZES}; total += sum(len(v) for v in d.values())
    lines.append(f'  {{ name: "{n}", s136: "{d[136]}", s48: "{d[48]}", s40: "{d[40]}" }},')
lines.append("];")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "pilots_data.ts")
open(out, "w").write("\n".join(lines) + "\n")
print(f"wrote {os.path.normpath(out)}: {len(ORDER)} pilots, {total / 1024:.0f} KB base64")
