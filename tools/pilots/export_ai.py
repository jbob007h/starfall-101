"""Build src/pilots_data.ts from the AI-generated raw portraits (16:9 jpgs): square crop centred on the head,
smooth LANCZOS resize to 136/48/40, stored as base64 JPEG (q88). Run from the repo root:
  python3 tools/pilots/export_ai.py /path/to/raw   (needs Pillow)"""
import base64, io, os, sys
from PIL import Image

RAW = sys.argv[1] if len(sys.argv) > 1 else "/workspace/portraits/ai_trial/raw"
# id order (0-12) and horizontal head centre as a fraction of the image width
ORDER = [("KAGE", 0.40), ("VOSS", 0.48), ("SABLE", 0.38), ("IRONCLAD", 0.50), ("HEX", 0.40), ("KRAG", 0.50), ("WRAITH", 0.50),
         ("FANG", 0.45), ("MARISOL", 0.44), ("BRICK", 0.50), ("TALON", 0.47), ("WIDOW", 0.50), ("JINX", 0.40)]


def crop(im, cx):
    W, H = im.size; s = H; x0 = max(0, min(W - s, int(W * cx - s / 2)))
    return im.crop((x0, 0, x0 + s, s))


def b64(img, q=88):
    buf = io.BytesIO(); img.save(buf, "JPEG", quality=q, optimize=True, progressive=False); return base64.b64encode(buf.getvalue()).decode()


lines = ["// GENERATED by tools/pilots/export_ai.py - do not edit. Pilot portraits (AI-generated art) as base64 JPEGs, resized per size.",
         "export const PILOT_IMAGES: { name: string; s136: string; s48: string; s40: string }[] = ["]
total = 0
for n, cx in ORDER:
    sq = crop(Image.open(os.path.join(RAW, n + ".jpg")).convert("RGB"), cx)
    d = {s: b64(sq.resize((s, s), Image.LANCZOS)) for s in (136, 48, 40)}; total += sum(len(v) for v in d.values())
    lines.append(f'  {{ name: "{n}", s136: "{d[136]}", s48: "{d[48]}", s40: "{d[40]}" }},')
lines.append("];")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "pilots_data.ts")
open(out, "w").write("\n".join(lines) + "\n")
print(f"wrote {os.path.normpath(out)}: {len(ORDER)} pilots, {total / 1024:.0f} KB base64")
